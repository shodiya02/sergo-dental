/* ============================================================
   ПЕР-МОДЕЛЬНЫЕ ФОТО-ПЕРЕОПРЕДЕЛЕНИЯ
   ------------------------------------------------------------
   Обычные правила в assets/photos.js работают ГЛОБАЛЬНО: они
   смотрят только на текст описания, поэтому одинаковые описания
   получают одинаковое фото на всех 26 страницах.

   Здесь можно задать фото ТОЛЬКО для одной модели — это не
   затронет остальные линейки.

   Ключ  — id страницы = имя html-файла без расширения,
           например "s320tr-continental".
           Можно указать и префикс семейства, например "s320tr" —
           применится ко всем s320tr-*.
           Точное совпадение имеет приоритет над префиксом.

   k     — массив подстрок описания в НИЖНЕМ регистре;
           достаточно совпадения одной из них.
   f     — путь к картинке, либо 'blank' (пустой квадрат),
           либо null (не показывать фото).

   Пример:
   var PHOTO_OVERRIDES = {
     "s320tr-continental": [
       { k: ["столик ассистента на двухшарнирном плече, регулируемый по высоте, на 5"],
         f: "assets/images/image_2026-07-29_10-49-50.png" }
     ],
     "s320tr": [
       { k: ["ems piezon"], f: "blank" }
     ]
   };
   ============================================================ */
